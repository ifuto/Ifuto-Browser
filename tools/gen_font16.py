for cp in (0x30D1, 0x30D4, 0x30D7, 0x30DA, 0x30DD):  # パピプペポ
    SYNTH[cp] = (cp - 2, 'h')
SYNTH[0x30F4] = (0x30A6, 'd')  # ヴ

DAKU_BITS = [(0, 6), (0, 7), (1, 6)]  # (row, col) — 右上の二点
HANDAKU_BITS = [(0, 6), (0, 7), (1, 5), (1, 7), (2, 6), (2, 7)]  # 右上の小環

def synth_glyph(base_rows, mark):
    rows = [bytearray(r, 'ascii') for r in base_rows]
    bits = DAKU_BITS if mark == 'd' else HANDAKU_BITS
    for r, c in bits:
        rows[r][c] = ord('#')
    return [bytes(r).decode('ascii') for r in rows]

# ---- 展開: 8x8 → 16x16（2x2 拡大）、16bit row (bit15=左列) ----
def rows16(rows8):
    out = []
    for r in rows8:
        v = 0
        for c in range(8):
            if r[c] == '#':
                v |= 0b11 << ((7 - c) * 2)
        out.extend((v, v))  # 縦も 2 倍
    assert len(out) == 16
    return out

def build():
    glyphs = {}   # cp -> [16 個の 16bit]
    for cp, rows in G.items():
        glyphs[cp] = rows16(rows)
    for cp, rows in EXTRA.items():
        glyphs[cp] = rows16(rows)
    for cp, (base, mark) in SYNTH.items():
        glyphs[cp] = rows16(synth_glyph(G[base], mark))
    return glyphs

def emit(glyphs, path):
    cps = sorted(glyphs)
    index = {}
    with open(path, 'w') as f:
        w = f.write
        w("/* Ifuto GUI — 自前全角 16x16 ドットフォント（機械生成: tools/gen_font16.py）\n")
        w(" * 直接編集禁止。対象: CJK 記号 + ひらがな + カタカナ（漢字は F16_TOFU 明示）。\n")
        w(" * 各グリフ 16 行 × 16bit（bit15=最左列）。1 グリフ = 2 セル (16x16px) ぶん。 */\n")
        w("#ifndef IFUTO_GUI_FONT16_H\n#define IFUTO_GUI_FONT16_H\n\n#include <stdint.h>\n\n")
        w("#define F16_BASE 0x3000u\n#define F16_SPAN 0x100u\n#define F16_ROWS 16\n")
        w("#define F16_NONE 0xFFu\n\n")
        w("static const uint16_t F16_GLYPHS[][F16_ROWS] = {\n")
        for i, cp in enumerate(cps):
            index[cp] = i
            w("    /* U+%04X */ {%s},\n" % (cp, ",".join("0x%04X" % r for r in glyphs[cp])))
        w("};\n\n")
        w("static const uint8_t F16_INDEX[F16_SPAN] = {")
        for cp in range(0x3000, 0x3100):
            v = index.get(cp, 0xFF)
            w("%s%d" % ("\n    " if cp % 16 == 0 else "", v))
            if cp != 0x30FF: w(",")
        w("\n};\n\n")
        extra = [cp for cp in cps if cp < 0x3000 or cp >= 0x3100]
        w("/* 0x3000 帯外の記号・図形・矢印（cp 昇順。二分探索） */\n")
        w("#define F16_N_EXTRA %d\n" % len(extra))
        w("static const uint16_t F16_EXTRA_CP[F16_N_EXTRA] = {%s};\n" %
          ",".join("0x%04X" % cp for cp in extra))
        w("static const uint8_t F16_EXTRA_SLOT[F16_N_EXTRA] = {%s};\n\n" %
          ",".join(str(index[cp]) for cp in extra))
        w("/* 未収録全角文字の豆腐（外枠 + 斜線: 「未対応」の明示印。「?」潰れ禁止規約） */\n")
        tofu = []
        for r in range(16):
            v = 0
            for c in range(16):
                edge = r in (0, 15) or c in (0, 15)
                diag = (r == c + 1) or (r == c - 1) or r == c
                if edge or (diag and 2 <= r <= 13 and 2 <= c <= 13):
                    v |= 0x8000 >> c
            tofu.append("0x%04X" % v)
        w("static const uint16_t F16_TOFU[F16_ROWS] = {%s};\n\n" % ",".join(tofu))
        w("static const uint16_t *f16_lookup(uint32_t cp) {\n")
        w("    if (cp >= F16_BASE && cp < F16_BASE + F16_SPAN) {\n")
        w("        uint8_t i = F16_INDEX[cp - F16_BASE];\n")
        w("        return i == F16_NONE ? NULL : F16_GLYPHS[i];\n")
        w("    }\n")
        w("    uint32_t lo = 0, hi = F16_N_EXTRA;\n")
        w("    while (lo < hi) {\n")
        w("        uint32_t mid = (lo + hi) / 2;\n")
        w("        if (F16_EXTRA_CP[mid] == cp) return F16_GLYPHS[F16_EXTRA_SLOT[mid]];\n")
        w("        if (F16_EXTRA_CP[mid] < cp) lo = mid + 1; else hi = mid;\n")
        w("    }\n")
        w("    return NULL;\n")
        w("}\n\n#endif\n")
    total = len(cps)
    print("%s: %d glyphs (%d base + %d synth), tofu 1" %
          (path, total, len(G), len(SYNTH)))

if __name__ == "__main__":
    import sys
    out = sys.argv[1] if len(sys.argv) > 1 else "src/gui/font16.h"
    emit(build(), out)
