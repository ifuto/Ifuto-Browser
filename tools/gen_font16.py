# ---- 濁音/半濁音の合成指定: cp → (ベース cp, mark)。mark: 'd' 濁点 / 'h' 半濁点 ----
SYNTH = {}
def _daku(start, end):   # 連続する濁音 cp 列（ベース = cp-1）
    for cp in range(start, end + 1, 2):
        SYNTH[cp] = (cp - 1, 'd')

_daku(0x304C, 0x3054)   # がぎぐげご
_daku(0x3056, 0x305E)   # ざじずぜぞ
for cp, b in ((0x3060,0x305F),(0x3062,0x3061),(0x3065,0x3064),(0x3067,0x3066),(0x3069,0x3068)):
    SYNTH[cp] = (b, 'd')   # だぢづでど（3063=っ が挟まり非等間隔）
for cp in (0x3070, 0x3073, 0x3076, 0x3079, 0x307C):  # ばびぶべぼ（は行は 3 周期）
    SYNTH[cp] = (cp - 1, 'd')
for cp in (0x3071, 0x3074, 0x3077, 0x307A, 0x307D):  # ぱぴぷぺぽ
    SYNTH[cp] = (cp - 2, 'h')
SYNTH[0x3094] = (0x3046, 'd')  # ゔ
